#!/usr/bin/env python3
"""Generate binary32 twiddles from high precision decimal Taylor series.
No numpy, vendor FFT, or platform libm in the generation path.
Pi is the Chudnovsky series evaluated at 100 decimal digits.
"""
from decimal import Decimal as D, localcontext
from pathlib import Path
import struct, sys

def make():
    with localcontext() as ctx:
        ctx.prec=100
        m=1; l=13591409; x=1; k=6; s=D(l)
        for i in range(1,9):
            m=m*(k*k*k-16*k)//(i*i*i); l+=545140134; x*= -262537412640768000
            s+=D(m*l)/D(x); k+=12
        pi=D(426880)*D(10005).sqrt()/s
        def trig(t,cos):
            term=D(1) if cos else t; total=term
            for j in range(1,150):
                term *= -t*t/D((2*j-1 if cos else 2*j)*(2*j if cos else 2*j+1)); total+=term
                if abs(term)<D('1e-95'): break
            return total
        words=[]
        for i in range(512):
            t=2*pi*i/1024
            re=trig(t,True); im=-trig(t,False)
            if i==0: re,im=D(1),D(0)
            if i==256: re,im=D(0),D(-1)
            words.extend(struct.unpack('<I',struct.pack('<f',float(v)))[0] for v in (re,im))
        return 'note SPDX-License-Identifier MIT\nnote Generated by tools/libraries/twiddles.py at 100 decimal digit precision\nglobal tw ulong 1024\nfn twinit to void\n'+''.join(f'put tw {i} {w}\n' for i,w in enumerate(words))+'end\n'
if __name__=='__main__':
    data=make()
    if len(sys.argv)>1: Path(sys.argv[1]).write_text(data)
    else: print(data,end='')
