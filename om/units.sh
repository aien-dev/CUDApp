# Regenerate every hosted and freestanding production Omega binding, or with
# --check require exact committed output (1 differs, 3 tools unavailable).
# Pure scalar lifecycle roots use the checked freest profile, not hosted imports.
#   OMEGA_OMC     seed-born omc (aien-dev/omega-mv seed/out/omc), sha256 pinned below
#   OMEGA_X86_OMC seed-born omc with the x86linux target (omega-mv main seed/out/omc), sha256 pinned below;
#                 without it only the AArch64 files are written or checked, and --check prints NOT_RUN for the x86 pair
#   OMEGA_BRIDGE  an aien-dev/omega-bridge checkout at om/omega-bridge.lock; src/native.om sha256 pinned below
# Generated by pinned src/native.om (ABI v1; hosted OM-1 and import-free freest):
#   src/cudapp_om_units.c          hosted unit machine code and checked bindings (AArch64)
#   src/cudapp_freest_units.c      scalar lifecycle code, no pthread/mmap/heap/TLS (AArch64)
#   src/cudapp_om_units_x86.c      the same hosted units compiled for x86linux (x86-64 SysV)
#   src/cudapp_freest_units_x86.c  the same freest units compiled for x86linux
#   src/cudapp_native.h            both profiles' public binding declarations (one header for both targets)
#   src/cudapp_om_units.ident      exact source/compiler/ABI/profile for every unit
# A unit or compiler that changes without regenerating these files fails --check (make test-om-units).
set -eu
OMC_PIN=2c82480596bbdc50cda9626866209ef662d5834f278f839ff4ce0250c495029f
X86_OMC_PIN=62775d2a391cfef7cde64e387655caa9809a267093112910ec76bfa568f3712b
NATIVE_PIN=5ccf97db9b46aea1fc580951d19e36423d94f545650496dcdb7acba99b983b6d
ROOT=$(cd "$(dirname "$0")/.." && pwd)
QUANT=om/quant/quant.om
REAL="$QUANT,om/components/realize.om"
CACHE="$REAL,om/cache/digest.om,om/cache/residency.om,om/cache/artifact.om"
PIPE="$CACHE,om/pipeline/select.om,om/pipeline/graph.om,om/pipeline/consume.om"
COMP="om/components/bw_alloc.om,om/components/bw_effect.om,om/components/bw_check.om,om/components/bw_project.om,om/components/rowpipe.om,om/components/staged.om,om/components/compose.om,om/components/runtime.om"
ENC="om/encoder/bw_enc_sm121.om,om/encoder/bw_spec_sm121.om,om/components/encode.om"
MOE="om/moe/moe_plan.om om/moe/moe_group.om om/moe/moe_ids32.om om/moe/moe_maps32.om om/moe/moe_segs32.om om/moe/moe_windows.om moe_admission=$PIPE,om/moe/moe_group.om,om/moe/moe_admit.om"
CLOSURE="$REAL,om/cache/digest.om,om/moe/moe_windows.om,om/moe/moe_group.om,native/learn53/moe-closure.om"
OBSERVE="closure_code=$CLOSURE,om/moe/closure_code.om closure_launch=$CLOSURE,om/moe/closure_launch.om closure_dir=$CLOSURE,om/moe/closure_dir.om closure_alloc=$CLOSURE,om/moe/closure_alloc.om closure_series=$CLOSURE,om/moe/closure_series.om"
UNITS="${OMEGA_UNITS:-om/encoder/bw_enc_sm121.om om/cubin/cubin_elf.om repack=$QUANT,om/quant/repack.om quant_wire=$QUANT,om/quant/runtime.om compose=$COMP encode=$ENC cache_runtime=om/cache/residency.om,om/cache/runtime.om lease=om/cache/residency.om,om/cache/runtime.om,om/cache/lease.om slotrev=om/cache/residency.om,om/cache/slotrev.om command=om/cache/residency.om,om/cache/command.om validate=$CACHE,$COMP,$ENC,om/components/admit.om,om/cache/validate.om digest=$REAL,om/cache/digest.om,om/cache/key.om code_digest=$REAL,om/cache/digest.om,om/cache/codekey.om templates=$REAL,om/cache/digest.om,om/cache/templates.om graph=$PIPE,om/pipeline/runtime.om context_lookup=om/pipeline/context.om,om/pipeline/context_abi.om binding=$REAL,om/pipeline/binding.om $MOE closure_pack=$CLOSURE,om/moe/closure_pack.om closure_bind=$CLOSURE,om/moe/closure_bind.om closure_blob=$CLOSURE,om/moe/closure_blob.om closure_cover=$CLOSURE,om/pipeline/mccover.om,om/pipeline/coverage_entry.om closure_intent=$CLOSURE,om/pipeline/mccover.om closure_seal=$CLOSURE,om/pipeline/mccover.om,om/pipeline/seal_entry.om $OBSERVE}"
PURE_UNITS="revision=om/pipeline/revision.om epoch=om/pipeline/epoch.om"
OUTS="cudapp_om_units.c cudapp_freest_units.c cudapp_native.h cudapp_om_units.ident"
X86_OUTS="cudapp_om_units_x86.c cudapp_freest_units_x86.c"
DEST="${OMEGA_UNITS_DEST:-$ROOT/src}"
[ -n "${OMEGA_OMC:-}" ] && [ -n "${OMEGA_BRIDGE:-}" ] || { echo "NOT_RUN: set OMEGA_OMC and OMEGA_BRIDGE"; exit 3; }
[ "$(sha256sum < "$OMEGA_OMC" | cut -c1-64)" = "$OMC_PIN" ] || { echo "NOT_RUN: omc is not the pinned compiler"; exit 3; }
[ "$(sha256sum < "$OMEGA_BRIDGE/src/native.om" | cut -c1-64)" = "$NATIVE_PIN" ] || { echo "NOT_RUN: native.om is not the pinned generator"; exit 3; }
X86=${OMEGA_X86_OMC:-}
if [ -n "$X86" ]; then
  [ "$(sha256sum < "$X86" | cut -c1-64)" = "$X86_OMC_PIN" ] || { echo "NOT_RUN: OMEGA_X86_OMC is not the pinned x86 compiler"; exit 3; }
  OUTS="$OUTS $X86_OUTS"
fi
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
"$OMEGA_OMC" < "$OMEGA_BRIDGE/src/native.om" > "$T/native"; chmod +x "$T/native"
"$OMEGA_OMC" < "$ROOT/om/function.om" > "$T/function"; chmod +x "$T/function"
: > "$T/hosted.in"; : > "$T/freest.in"; : > "$T/hosted.x86.in"; : > "$T/freest.x86.in"; : > "$T/cudapp_om_units.ident"
for profile in OM-1 freest; do
  case "$profile" in
    OM-1) units=$UNITS; frame=hosted.in ;;
    freest) units=$PURE_UNITS; frame=freest.in ;;
  esac
for u in $units; do
  case "$u" in
    *=*) name=${u%%=*}; parts=${u#*=} ;;
    *) name=$(basename "$u" .om | tr -c 'A-Za-z0-9_\n' '_'); parts=$u ;;
  esac
  : > "$T/unit.om"
  old_ifs=$IFS; IFS=,
  for part in $parts; do
    case "$part" in /*) src=$part ;; *) src=$ROOT/$part ;; esac
    cat "$src" >> "$T/unit.om"
    printf '\n' >> "$T/unit.om"
  done
  IFS=$old_ifs
  printf 'generating native unit %s\n' "$name"
  "$OMEGA_OMC" < "$T/unit.om" > "$T/u.bin"
  "$T/function" < "$T/u.bin" || { echo "REFUSED: $name is not a native function image" >&2; exit 3; }
  { cat "$T/unit.om"; printf '\0'; printf '%08d' "$(wc -c < "$T/u.bin")"; cat "$T/u.bin"; } >> "$T/$frame"
  if [ -n "$X86" ]; then
    # The target line selects the x86linux back end; the frame carries the unit source without it, as tools/native does.
    { printf 'target x86linux\n'; cat "$T/unit.om"; } | "$X86" > "$T/u.x86.bin"
    "$T/function" < "$T/u.x86.bin" || { echo "REFUSED: $name is not a native x86 function image" >&2; exit 3; }
    { cat "$T/unit.om"; printf '\0'; printf '%08d' "$(wc -c < "$T/u.x86.bin")"; cat "$T/u.x86.bin"; } >> "$T/${frame%.in}.x86.in"
  fi
  echo "omega-ident 1 unit=$name abi=1 profile=$profile src=$(sha256sum < "$T/unit.om" | cut -c1-64) omc=$OMC_PIN path=$parts" >> "$T/cudapp_om_units.ident"
done
done
"$T/native" c < "$T/hosted.in" > "$T/cudapp_om_units.c"
"$T/native" freest < "$T/freest.in" > "$T/cudapp_freest_units.c"
cat "$T/hosted.in" "$T/freest.in" > "$T/units.in"
"$T/native" h < "$T/units.in" > "$T/cudapp_native.h"
if [ -n "$X86" ]; then
  "$T/native" c x86linux < "$T/hosted.x86.in" > "$T/cudapp_om_units_x86.c"
  "$T/native" freest x86linux < "$T/freest.x86.in" > "$T/cudapp_freest_units_x86.c"
  # One committed header serves both targets, so the x86 frames must declare exactly the same bindings.
  cat "$T/hosted.x86.in" "$T/freest.x86.in" | "$T/native" h x86linux > "$T/native_x86.h"
  cmp -s "$T/native_x86.h" "$T/cudapp_native.h" || { echo "REFUSED: the x86 frames declare a different src/cudapp_native.h" >&2; exit 3; }
fi
if [ "${1:-}" = --check ]; then
  bad=0
  for f in $OUTS; do cmp -s "$T/$f" "$DEST/$f" || { echo "FAIL src/$f differs from the pinned tools' output"; bad=1; }; done
  [ $bad = 0 ] || exit 1
  echo "PASS src/{$(echo $OUTS | tr ' ' ,)} regenerate byte for byte"
  [ -n "$X86" ] || echo "NOT_RUN src/{$(echo $X86_OUTS | tr ' ' ,)}: set OMEGA_X86_OMC to check the x86 bindings (this PASS does not cover them)"
  exit 0
fi
for f in $OUTS; do cp "$T/$f" "$DEST/$f"; done; echo "wrote $DEST/{$(echo $OUTS | tr ' ' ,)}"
